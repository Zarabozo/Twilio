package Twilio::Generator::TwiML;

use 5.016;
use warnings;

use Carp     qw(croak);
use JSON::PP ();

use Twilio::Generator::Pod;

our $VERSION = '2.000000';

# Every element has these, so an element or attribute with one of these names would replace them.
my %IS_RESERVED =
  map { $_ => 1 }
  qw(DESTROY add_child append as_xml attribute_table can isa nest new set_attribute);

# The three documents a webhook returns are where people start, so they get a real example and a
# word on their use; t/manual.t checks that each example writes what it says.
my %ROOT_POD = (
  VoiceResponse => {
    about => 'The root of the TwiML that tells Twilio what to do with a call. Return it '
      . 'from the webhook of a phone number, or pass it as C<twiml> when you make a call. '
      . 'See L<Twilio::Manual> for a whole webhook.',
    example => <<'END_EXAMPLE',
  use Twilio::TwiML::VoiceResponse;

  my $response = Twilio::TwiML::VoiceResponse->new;
  $response->say('Thanks for calling!', { voice => 'Polly.Joanna' });
  my $gather = $response->gather(
    { input => [qw(dtmf speech)], action => '/menu', num_digits => 1 });
  $gather->say('Press 1 for sales, or 2 for support.');
  $response->redirect('/voice');

  print "Content-Type: text/xml\n\n", $response;

  # <?xml version="1.0" encoding="UTF-8"?>
  # <Response><Say voice="Polly.Joanna">Thanks for calling!</Say><Gather action="/menu"
  # input="dtmf speech" numDigits="1"><Say>Press 1 for sales, or 2 for
  # support.</Say></Gather><Redirect>/voice</Redirect></Response>
END_EXAMPLE
  },
  MessagingResponse => {
    about => 'The root of the TwiML that tells Twilio how to answer a message. Return it from '
      . 'the webhook of a phone number. See L<Twilio::Manual> for a whole webhook.',
    example => <<'END_EXAMPLE',
  use Twilio::TwiML::MessagingResponse;

  my $response = Twilio::TwiML::MessagingResponse->new;
  $response->message('The Robots are coming! Head for the hills!');

  # With a picture
  my $message = $response->message;
  $message->body('Here is a picture.');
  $message->media('https://demo.twilio.com/owl.png');

  print "Content-Type: text/xml\n\n", $response;
END_EXAMPLE
  },
  FaxResponse => {
    about => 'The root of the TwiML that tells Twilio what to do with an incoming fax. Return '
      . 'it from the fax webhook of a phone number.',
    example => <<'END_EXAMPLE',
  use Twilio::TwiML::FaxResponse;

  my $response = Twilio::TwiML::FaxResponse->new;
  $response->receive({ action => '/fax/received', media_type => 'application/pdf' });

  print "Content-Type: text/xml\n\n", $response;

  # <?xml version="1.0" encoding="UTF-8"?>
  # <Response><Receive action="/fax/received" mediaType="application/pdf"/></Response>
END_EXAMPLE
  },
);

sub root_pod { return \%ROOT_POD }

sub load {
  my ($file) = @_;

  open my $handle, '<:raw', $file or croak "Cannot read $file: $!";
  my $content = do { local $/ = undef; <$handle> };
  close $handle or croak "Cannot read $file: $!";
  return JSON::PP->new->utf8->decode($content);
}

# Returns the code of each module, by the path of its file under lib.
sub modules {
  my ($elements) = @_;

  my %code;
  for my $name (sort keys %{$elements}) {
    my $module = "Twilio::TwiML::$name";
    $code{ ($module =~ s{::}{/}gr) . '.pm' } = module($module, $name, $elements->{$name});
  }
  return \%code;
}

sub module {
  my ($module, $name, $element) = @_;

  _check_names($name, $element);
  return join "\n", _header($module), _table($element), _constructor($element),
    (map { _child($_) } @{ $element->{children} }),
    (map { _setter($_) } @{ $element->{attributes} }), "1;\n", "__END__\n",
    _pod($module, $name, $element);
}

sub _check_names {
  my ($name, $element) = @_;

  my %seen;
  for my $method (
    (map { $_->{method} } @{ $element->{children} }),
    map { $_->{method} } @{ $element->{attributes} }
    )
  {
    croak "$name: method $method is reserved"     if $IS_RESERVED{$method};
    croak "$name: two methods are called $method" if $seen{$method}++;
  }
  return;
}

sub _header {
  my ($module) = @_;
  return <<"END_CODE";
# Generated by tools/generate.pl from tools/twiml-elements.json. Do not edit this file.
package $module;

use 5.016;
use warnings;

use parent 'Twilio::TwiML::TwiML';

our \$VERSION = '2.000000';
END_CODE
}

sub _table {
  my ($element) = @_;

  my @attributes = @{ $element->{attributes} };
  return q{} if !@attributes;

  my @lines;
  for my $attribute (@attributes) {
    my $type  = $attribute->{type} eq 'boolean' ? q{, boolean => 1} : q{};
    my $entry = "{ name => '$attribute->{wire}'$type }";
    my @keys =
      ($attribute->{name}, $attribute->{wire} ne $attribute->{name} ? $attribute->{wire} : ());
    push @lines, map { "  '$_' => $entry,\n" } @keys;
  }
  my $table = join q{}, @lines;

  return <<"END_CODE";
my %ATTRIBUTES = (
$table);

sub attribute_table { return \\%ATTRIBUTES }
END_CODE
}

sub _constructor {
  my ($element) = @_;

  my $value      = $element->{value};
  my $attributes = $element->{has_attributes};
  my $signature  = join q{, }, '$class', defined $value ? "\$$value" : (),
    $attributes ? '$attributes' : ();
  my $arguments = join q{, }, "'$element->{tag}'", defined $value ? "\$$value" : 'undef',
    $attributes ? '$attributes' : ();

  return <<"END_CODE";
sub new {
  my ($signature) = \@_;
  return \$class->SUPER::new($arguments);
}
END_CODE
}

sub _child {
  my ($child) = @_;

  my $class = "Twilio::TwiML::$child->{class}";
  my @names = (
    defined $child->{value}  ? "\$$child->{value}" : (),
    $child->{has_attributes} ? '$attributes'       : ()
  );
  my $list      = join q{, }, @names;
  my $signature = join q{, }, '$self', @names;

  # Record is a verb of TwiML, so this name has to stay, unclear as critic finds it in general.
  my $note = $child->{method} eq 'record' ? '    ## no critic (ProhibitAmbiguousNames)' : q{};

  return <<"END_CODE";
sub $child->{method} {$note
  my ($signature) = \@_;
  require $class;
  return \$self->nest($class->new($list));
}
END_CODE
}

sub _setter {
  my ($attribute) = @_;

  return <<"END_CODE";
sub $attribute->{method} {
  my (\$self, \$value) = \@_;
  return \$self->set_attribute('$attribute->{name}', \$value);
}
END_CODE
}

sub _pod {
  my ($module, $name, $element) = @_;

  my $tag      = $element->{tag};
  my @children = @{ $element->{children} };
  my @setters  = @{ $element->{attributes} };

  my $call = join q{, }, defined $element->{value} ? "\$$element->{value}" : (),
    $element->{has_attributes} ? '\%attributes' : ();

  my $root = $ROOT_POD{$name};
  my @pod  = (
    "=encoding UTF-8\n",
    "=head1 NAME\n",
    "$module - The $tag element of TwiML\n",
    "=head1 SYNOPSIS\n",
    $root ? $root->{example} : "  my \$element = $module->new($call);\n",
    "=head1 DESCRIPTION\n",
    ($root ? "$root->{about}\n" : ()),
    "See L<Twilio::TwiML::TwiML> for the methods every element has.\n",
    "=head1 METHODS\n",
    "=head2 new\n",
    "  my \$element = $module->new($call);\n",
  );
  if (@setters) {
    push @pod, "=head2 attribute_table\n", "Used by L<Twilio::TwiML::TwiML>.\n";
  }
  for my $child (@children) {
    my @arguments = (
      defined $child->{value}  ? "\$$child->{value}" : (),
      $child->{has_attributes} ? '\%attributes'      : ()
    );
    my $arguments = join q{, }, @arguments;
    push @pod, "=head2 $child->{method}\n",
      "  my \$child = \$element->$child->{method}($arguments);\n",
      Twilio::Generator::Pod::text($child->{about})
      . " Returns a L<Twilio::TwiML::$child->{class}>.\n";
  }
  if (@setters) {
    push @pod, "=head1 ATTRIBUTES\n",
      "Each name works in C<\\%attributes>, and as a C<set_> method that returns the element.\n",
      "=over\n";
    push @pod, map { _attribute_pod($_) } @setters;
    push @pod, "=back\n", map { "=head2 $_->{method}\n" } @setters;
    push @pod, "Set the attribute of the same name.\n";
  }
  return join "\n", @pod, Twilio::Generator::Pod::end();
}

sub _attribute_pod {
  my ($attribute) = @_;

  my $about = Twilio::Generator::Pod::text($attribute->{about});
  my $type  = $attribute->{type};
  $about .= ' True or false.'      if $type eq 'boolean';
  $about .= ' An array reference.' if $type eq 'list';
  return "=item C<$attribute->{name}>\n", "$about\n";
}

1;
